"""
TenantMeteringPlugin - Per-Tenant Usage Metering via Strands Plugin
Module 3, Lab 5

A Strands Agent Plugin that automatically captures per-tenant usage metrics
by hooking into the agent lifecycle. Emits CloudWatch metrics via
put_metric_data with a TenantId dimension.

Hooks:
  - AfterInvocationEvent: captures token usage, latency, and cycle count from
    the agent's accumulated metrics after each full invocation completes
  - AfterToolCallEvent: captures tool name and invocation count per tool call

Metrics emitted:
  - InputTokens: tokens sent to the model (per invocation)
  - OutputTokens: tokens generated by the model (per invocation)
  - TotalTokens: input + output for cost estimation
  - LatencyMs: model response latency in milliseconds
  - CycleCount: number of agent reasoning cycles (model calls per invocation)
  - InvocationCount: request count (always 1 per emission)
  - ToolInvocations: count per tool name

How token tracking works:
  Strands internally tracks token usage via EventLoopMetrics. After each model
  call, the framework updates accumulated_usage with inputTokens and outputTokens
  from the Bedrock Converse API response. The AfterInvocationEvent fires after
  the full agent loop completes (potentially multiple model calls + tool calls),
  giving us the total tokens consumed for that request.

Usage:
    from tenant_metering_plugin import TenantMeteringPlugin

    metering = TenantMeteringPlugin(tenant_id="tenant-001")
    agent = Agent(model=model, plugins=[metering])
"""

import json
import os
import time

from strands.plugins import Plugin, hook
from strands.hooks import AfterInvocationEvent, AfterToolCallEvent

# CloudWatch namespace for all tenant metering metrics
_METRIC_NAMESPACE = "SaaS/AgentMetering"


def _default_model_id() -> str:
    """Return the model ID from environment or default."""
    return os.environ.get("BEDROCK_MODEL_ID", "amazon.nova-pro-v1:0")


class TenantMeteringPlugin(Plugin):
    """
    Strands Plugin that emits per-tenant usage metrics to CloudWatch via put_metric_data.

    Attaches to the agent at initialization and automatically captures:
    - Token usage (input/output) after each agent invocation completes
    - Tool invocation counts after every tool call

    All metrics include a TenantId dimension for per-tenant dashboards and billing.
    """

    name = "tenant-metering"

    def __init__(self, tenant_id: str, model_id: str = None, agent_name: str = None):
        super().__init__()
        self.tenant_id = tenant_id
        self.model_id = model_id or _default_model_id()
        self.agent_name = agent_name or os.environ.get("AGENT_NAME", "default")

    # ------------------------------------------------------------------
    # Task 5.3a: Emit token usage metrics after agent invocation
    # ------------------------------------------------------------------

    @hook
    def on_invocation_complete(self, event: AfterInvocationEvent) -> None:
        """
        Called after the full agent invocation completes (all model calls
        and tool calls for this request). Reads the accumulated token usage
        and performance metrics from the agent's EventLoopMetrics and emits
        per-tenant metrics.

        Metrics emitted:
          - InputTokens: tokens sent to the model
          - OutputTokens: tokens generated by the model
          - TotalTokens: input + output (for cost estimation)
          - LatencyMs: model response latency
          - CycleCount: number of reasoning cycles (model calls)
          - InvocationCount: always 1 (for counting total invocations)
        """
        # TODO: Task 5.3a - Emit token usage metrics after invocation
        if not event.agent:
            return

        metrics = event.agent.event_loop_metrics
        latest = metrics.latest_agent_invocation
        if not latest or not latest.usage:
            return

        input_tokens = latest.usage.get("inputTokens", 0)
        output_tokens = latest.usage.get("outputTokens", 0)

        self._emit_metrics({
            "InputTokens": input_tokens,
            "OutputTokens": output_tokens,
            "TotalTokens": input_tokens + output_tokens,
            "LatencyMs": metrics.accumulated_metrics.get("latencyMs", 0),
            "CycleCount": len(latest.cycles) if latest.cycles else 1,
            "InvocationCount": 1,
        })
    # ------------------------------------------------------------------
    # Task 5.3b: Emit tool invocation metric after tool call
    # ------------------------------------------------------------------

    @hook
    def on_tool_complete(self, event: AfterToolCallEvent) -> None:
        """
        Called after every tool call. Emits a count metric with the tool name
        as an additional dimension for per-tool-per-tenant tracking.
        """
        # TODO: Task 5.3b - Emit tool invocation metric after tool call
        tool_name = event.tool_use.get("name", "unknown")
        self._emit_metrics(
            {"ToolInvocations": 1},
            extra_dimensions={"ToolName": tool_name},
        )
    # ------------------------------------------------------------------
    # EMF emission helper (provided)
    # ------------------------------------------------------------------

    def _emit_metrics(self, metrics: dict, extra_dimensions: dict = None):
        """
        Emit metrics directly to CloudWatch via put_metric_data.

        Uses the CloudWatch API directly since AgentCore Runtime log events
        combine stdout into single events (preventing EMF extraction).

        Args:
            metrics: Dict of metric_name -> value to emit.
            extra_dimensions: Additional dimensions beyond TenantId and Model.
        """
        dimensions = [
            {"Name": "Agent", "Value": self.agent_name},
            {"Name": "TenantId", "Value": self.tenant_id},
            {"Name": "Model", "Value": self.model_id},
        ]
        if extra_dimensions:
            for k, v in extra_dimensions.items():
                dimensions.append({"Name": k, "Value": v})

        metric_data = []
        for name, value in metrics.items():
            metric_data.append({
                "MetricName": name,
                "Value": float(value),
                "Unit": "Count",
                "Dimensions": dimensions,
            })

        try:
            import boto3
            cw = boto3.client("cloudwatch", region_name=os.environ.get("AWS_REGION", "us-east-1"))
            cw.put_metric_data(
                Namespace=_METRIC_NAMESPACE,
                MetricData=metric_data,
            )
        except Exception as e:
            # Don't fail the agent if metrics emission fails
            print(f"[metering] WARNING: Failed to emit metrics: {e}")
